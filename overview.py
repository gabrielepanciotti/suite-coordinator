# overview.py
"""Node overview endpoint — live scheda-nodo for the Coordinator.

A single read-only endpoint (GET /api/overview) that merges the static
``overview.manifest.json`` (generated by the ``scheda-nodo`` skill /
``node-overview`` command) with a **live** ``database`` section produced by
querying ``information_schema.tables`` and ``SELECT count(*)`` on every
applicative table of the optional per-node Postgres (``DATABASE_URL``).

Public like the rest of this LAN-only API (no auth layer here — mirrors the
/api/health convention of other Life nodes): it carries no secrets, only
identity/functionality/DB-row-count metadata, so other Life nodes can
introspect the node freely.

Degrades gracefully:
- manifest absent  -> minimal identity, ``live: false`` + ``warning``;
- DATABASE_URL unset or DB down -> ``database.error``, rest served normally.

Pure logic + FastAPI router; mounted on api.app (port :10001). Never imports
bot.py (acyclic, same rule as a2a_webhook).
"""
from __future__ import annotations

import asyncio
import json
import logging
import os
from pathlib import Path
from typing import Any

from fastapi import APIRouter

logger = logging.getLogger("coordinator.overview")

router = APIRouter()

_MANIFEST_PATH = Path(__file__).resolve().parent / "overview.manifest.json"

# Tables that are part of the migration infrastructure, not app data.
_EXCLUDED_TABLES: frozenset[str] = frozenset({"alembic_version"})


def _load_manifest() -> dict[str, Any] | None:
    """Return the parsed manifest or ``None`` if absent/corrupt."""
    if not _MANIFEST_PATH.exists():
        return None
    try:
        return json.loads(_MANIFEST_PATH.read_text(encoding="utf-8"))
    except Exception:
        logger.exception("overview: failed to parse manifest at %s", _MANIFEST_PATH)
        return None


def _query_database_section(highlight_specs: list[dict[str, str]]) -> dict[str, Any]:
    """Live ``{"tables": [...], "highlights": [...]}`` from the per-node DB.

    Synchronous (SQLAlchemy sync engine, per db/session.py) — callers run it
    in a thread. Table names come from ``information_schema`` and are quoted
    as identifiers so exotic names can't break or inject the statement.
    On any failure the section carries only a generic ``error``.
    """
    try:
        from sqlalchemy import text

        from db.session import session_scope

        with session_scope() as session:
            result = session.execute(text(
                """
                SELECT table_name
                FROM information_schema.tables
                WHERE table_schema = 'public'
                  AND table_type = 'BASE TABLE'
                ORDER BY table_name
                """
            ))
            table_names: list[str] = [row[0] for row in result.fetchall()]

            rows: list[dict[str, Any]] = []
            counts: dict[str, int] = {}
            for tname in table_names:
                if tname in _EXCLUDED_TABLES:
                    continue
                safe_name = tname.replace('"', '""')
                count = session.execute(
                    text(f'SELECT count(*) FROM "{safe_name}"')
                ).scalar_one()
                rows.append({"name": tname, "rows": count})
                counts[tname] = count

        highlights: list[dict[str, Any]] = []
        for spec in highlight_specs:
            tname = spec.get("name", "")
            label = spec.get("label", tname)
            if tname in counts:
                highlights.append({"label": label, "value": counts[tname]})

        return {"tables": rows, "highlights": highlights}
    except Exception:
        # Full traceback server-side only; never leak SQL/DSN to callers.
        logger.exception("overview: DB section query failed")
        return {"tables": [], "highlights": [], "error": "database query failed"}


async def build_overview() -> dict[str, Any]:
    """Assemble the full scheda-nodo payload (manifest + live DB section)."""
    manifest = await asyncio.to_thread(_load_manifest)
    if manifest is None:
        return {
            "live": False,
            "identity": {
                "slug": "coordinator",
                "name": "Coordinator",
                "type": os.environ.get("NODE_TYPE", "bridge"),
            },
            "warning": (
                "overview.manifest.json missing — run the scheda-nodo skill "
                "(suite_core.nodes node-overview) to generate it"
            ),
        }

    highlight_specs = manifest.get("overview", {}).get("highlights", [])
    database = await asyncio.to_thread(_query_database_section, highlight_specs)
    payload: dict[str, Any] = dict(manifest)
    payload["database"] = database
    payload["live"] = "error" not in database
    return payload


@router.get("/api/health")
def health() -> dict[str, str]:
    """Liveness probe (public, no auth) — Life node convention."""
    return {"status": "ok", "node": "coordinator"}


@router.get(
    "/api/overview",
    summary="Scheda nodo: identità, funzioni, collaborazioni, DB live, brain",
)
async def get_overview() -> dict[str, Any]:
    """Return the full node overview payload.

    Always responds 200; partial failures are indicated by ``live: false``
    or a ``database.error`` field.
    """
    return await build_overview()
