#!/usr/bin/env python3
"""Give every workspace `.venv` a container-side copy of its own (issue #47).

The bot bind-mounts the host repos under /workspaces. A `.venv` inside a repo is
therefore ONE directory seen from two sides, but a venv only works from the side
that built it: its interpreter link and shebangs are absolute paths
(`/usr/local/bin/python3` in the container, `${HOME}/…` on the host). An agent
in the container that finds the host venv unusable does the reasonable thing —
recreates it — and breaks every host service running on it. Measured 2026-09-21:
Network's `.venv` rebuilt from inside, `hub-listener.service` dead at the next
restart with `status=203/EXEC`, and nothing said so.

The fix is a mount: inside the container each existing `.venv` is covered by a
host directory of its own, outside the repo. The container sees an empty venv
it may rebuild at will; the host one is never reachable from there.

Why generated and not written into docker-compose.yml:
  * the list is per-device — which repos exist, and which of them have a `.venv`
    (also in `backend/`), is a fact of this box, not of the code;
  * a mask is only safe where the `.venv` already exists on the host. Docker
    creates a missing mount point itself, as root, inside the bind-mounted repo:
    the host would find a root-owned empty `.venv` it cannot build into.
  * the mask source must exist and belong to the device user (uid 1000 == `app`
    in the container), or Docker creates it root-owned and the container cannot
    write into its own venv. This script creates it first.

Output: `docker-compose.override.yml` next to the compose file, which
`docker compose` loads on its own. It is gitignored (per-device) and carries a
marker line: a hand-written override is never overwritten.

    python3 scripts/gen_venv_masks.py            # write the override
    python3 scripts/gen_venv_masks.py --check    # exit 1 if missing/stale
    docker compose up -d coordinator-bot                     # apply (recreate, not restart)
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
MARKER = "# generated by scripts/gen_venv_masks.py (issue #47) — do not edit"
DEFAULT_MASK_ROOT = "~/.local/share/coordinator/venv-masks"

# `- ${WS_X:-default}:/workspaces/x` (also nested targets, never :ro mounts).
_MOUNT = re.compile(
    r"^\s*-\s*\$\{(?P<var>[A-Z_][A-Z0-9_]*)(?::-[^}]*)?\}:(?P<target>/workspaces/[^\s:]+)\s*$"
)
# Directories that never contain a project venv worth masking, and are huge.
_SKIP = {".git", "node_modules", ".venv", "venv", "__pycache__", "old", "worktrees"}


def parse_env(text: str) -> dict[str, str]:
    """Minimal .env reader: KEY=VALUE, comments and blanks ignored."""
    env: dict[str, str] = {}
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        env[key.strip()] = value.strip().strip('"').strip("'")
    return env


def workspace_mounts(compose_text: str) -> list[tuple[str, str]]:
    """(env var, container target) for every workspace bind-mount."""
    out = []
    for line in compose_text.splitlines():
        m = _MOUNT.match(line)
        if m:
            out.append((m["var"], m["target"]))
    return out


def find_venvs(root: Path, max_depth: int = 3) -> list[Path]:
    """`.venv` directories under root, as paths relative to it."""
    found: list[Path] = []

    def walk(d: Path, depth: int) -> None:
        try:
            entries = sorted(d.iterdir())
        except OSError:
            return
        for e in entries:
            if not e.is_dir() or e.is_symlink():
                continue
            if e.name == ".venv":
                found.append(e.relative_to(root))
            elif depth < max_depth and e.name not in _SKIP:
                walk(e, depth + 1)

    walk(root, 1)
    return found


def mask_name(host_venv: Path) -> str:
    """Stable, flat directory name, keyed by the HOST venv: a repo mounted at
    two targets (launcher/dashboard) gets one container venv, not two."""
    return host_venv.as_posix().strip("/").replace("/", "__")


def plan(
    mounts: list[tuple[str, str]], env: dict[str, str], mask_root: Path
) -> list[tuple[Path, str]]:
    """(host mask dir, container .venv path), one per venv found."""
    out: dict[str, Path] = {}
    for var, target in mounts:
        host = env.get(var)
        if not host:
            continue  # placeholder mount: nothing real behind it
        root = Path(os.path.expanduser(host))
        if not root.is_dir():
            continue
        for rel in find_venvs(root):
            dest = f"{target}/{rel.as_posix()}"
            out.setdefault(dest, mask_root / mask_name(root / rel))
    return [(src, dest) for dest, src in sorted(out.items())]


def render(entries: list[tuple[Path, str]]) -> str:
    lines = [MARKER, "services:", "  coordinator-bot:", "    volumes:"]
    if not entries:
        lines[-1] = "    volumes: []"
    lines += [f"      - {src}:{dest}" for src, dest in entries]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if missing or stale")
    ap.add_argument("--compose-dir", type=Path, default=REPO)
    args = ap.parse_args(argv)

    base = args.compose_dir
    env_file = base / ".env"
    env = parse_env(env_file.read_text(encoding="utf-8")) if env_file.is_file() else {}
    env = {**env, **{k: v for k, v in os.environ.items() if k.startswith("WS_")}}
    mask_root = Path(
        os.path.expanduser(env.get("VENV_MASK_ROOT") or os.environ.get("VENV_MASK_ROOT") or DEFAULT_MASK_ROOT)
    )
    entries = plan(
        workspace_mounts((base / "docker-compose.yml").read_text(encoding="utf-8")),
        env,
        mask_root,
    )
    content = render(entries)
    out = base / "docker-compose.override.yml"
    current = out.read_text(encoding="utf-8") if out.is_file() else None

    if args.check:
        if current != content:
            print(f"venv masks stale or missing: rerun {Path(__file__).name}", file=sys.stderr)
            return 1
        print(f"venv masks up to date ({len(entries)})")
        return 0

    if current is not None and not current.startswith(MARKER):
        print(f"{out} exists and was not generated here: refusing to overwrite", file=sys.stderr)
        return 2
    for src, _ in entries:
        src.mkdir(parents=True, exist_ok=True)
    out.write_text(content, encoding="utf-8")
    print(f"{len(entries)} venv masks -> {out}")
    for src, dest in entries:
        print(f"  {dest}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
